// ============================================================
// 数据表格（搜索 + 排序 + 分页）
// ============================================================
const PAGE_SIZE = 20;
let currentPage = 1;
let sortCol = -1;
let sortAsc = true;
let filteredData = [...dividendData];

function initTable() {
    renderTable();
    bindTableEvents();
}

function bindTableEvents() {
    // 搜索
    document.getElementById('tableSearch').addEventListener('input', function(e) {
        const keyword = e.target.value.trim().toLowerCase();
        if (!keyword) {
            filteredData = [...dividendData];
        } else {
            filteredData = dividendData.filter(row =>
                row[0].toLowerCase().includes(keyword) ||
                row[1].toLowerCase().includes(keyword)
            );
        }
        currentPage = 1;
        renderTable();
    });

    // 排序
    document.querySelectorAll('.data-table th').forEach(th => {
        th.addEventListener('click', function() {
            const col = parseInt(this.dataset.col);
            if (sortCol === col) {
                sortAsc = !sortAsc;
            } else {
                sortCol = col;
                sortAsc = true;
            }
            updateSortIcons();
            renderTable();
        });
    });

    // 分页
    document.getElementById('prevPage').addEventListener('click', function() {
        if (currentPage > 1) { currentPage--; renderTable(); }
    });
    document.getElementById('nextPage').addEventListener('click', function() {
        const totalPages = Math.ceil(filteredData.length / PAGE_SIZE);
        if (currentPage < totalPages) { currentPage++; renderTable(); }
    });
}

function updateSortIcons() {
    document.querySelectorAll('.data-table th').forEach(th => {
        th.classList.remove('sorted-asc', 'sorted-desc');
    });
    if (sortCol >= 0) {
        const th = document.querySelector(`.data-table th[data-col="${sortCol}"]`);
        if (th) {
            th.classList.add(sortAsc ? 'sorted-asc' : 'sorted-desc');
        }
    }
}

function renderTable() {
    // 排序
    let data = [...filteredData];
    if (sortCol >= 0) {
        data.sort((a, b) => {
            let va = a[sortCol];
            let vb = b[sortCol];
            // 尝试数值比较
            const na = parseFloat(va);
            const nb = parseFloat(vb);
            if (!isNaN(na) && !isNaN(nb)) {
                return sortAsc ? na - nb : nb - na;
            }
            return sortAsc
                ? String(va).localeCompare(String(vb), 'zh')
                : String(vb).localeCompare(String(va), 'zh');
        });
    }

    const totalPages = Math.max(1, Math.ceil(data.length / PAGE_SIZE));
    if (currentPage > totalPages) currentPage = totalPages;

    const start = (currentPage - 1) * PAGE_SIZE;
    const pageData = data.slice(start, start + PAGE_SIZE);

    const tbody = document.getElementById('tableBody');
    tbody.innerHTML = pageData.map(row => {
        const progressBadge = row[7] === '实施'
            ? '<span class="badge badge-ok">实施</span>'
            : row[7] === '预案'
            ? '<span class="badge badge-warn">预案</span>'
            : '<span class="badge badge-none">' + row[7] + '</span>';
        return '<tr>' +
            '<td>' + row[0] + '</td>' +
            '<td>' + row[1] + '</td>' +
            '<td>' + row[2] + '</td>' +
            '<td>' + row[3] + '</td>' +
            '<td>' + row[4] + '</td>' +
            '<td>' + row[5] + '</td>' +
            '<td>' + row[6] + '</td>' +
            '<td>' + progressBadge + '</td>' +
            '<td>' + (row[8] || '—') + '</td>' +
            '</tr>';
    }).join('');

    document.getElementById('tableInfo').textContent =
        '共 ' + data.length + ' 条记录';
    document.getElementById('pageInfo').textContent =
        '第 ' + currentPage + ' / ' + totalPages + ' 页';
    document.getElementById('prevPage').disabled = currentPage <= 1;
    document.getElementById('nextPage').disabled = currentPage >= totalPages;
}
